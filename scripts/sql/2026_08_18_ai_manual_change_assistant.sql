CREATE TABLE IF NOT EXISTS ipca_manual_ai_decisions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  project_id BIGINT UNSIGNED NOT NULL,
  finding_id BIGINT UNSIGNED NULL,
  requirement_id BIGINT UNSIGNED NULL,
  decision VARCHAR(24) NOT NULL COMMENT 'approved | rejected | deferred | accepted',
  note TEXT NULL,
  decided_by INT NOT NULL,
  decided_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uk_imad_finding (finding_id),
  UNIQUE KEY uk_imad_requirement (requirement_id),
  KEY idx_imad_project (project_id, decided_at),
  CONSTRAINT fk_imad_project FOREIGN KEY (project_id) REFERENCES ipca_manual_ai_projects(id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_imad_finding FOREIGN KEY (finding_id) REFERENCES ipca_manual_ai_findings(id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_imad_requirement FOREIGN KEY (requirement_id) REFERENCES ipca_manual_ai_requirements(id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_imad_user FOREIGN KEY (decided_by) REFERENCES users(id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ipca_manual_ai_jobs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  project_id BIGINT UNSIGNED NOT NULL,
  job_type VARCHAR(32) NOT NULL DEFAULT 'analysis',
  idempotency_key CHAR(64) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'queued' COMMENT 'queued | running | completed | retry | failed',
  attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
  max_attempts INT UNSIGNED NOT NULL DEFAULT 3,
  progress_percent TINYINT UNSIGNED NOT NULL DEFAULT 0,
  lease_token CHAR(36) NULL,
  lease_expires_at DATETIME NULL,
  available_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ai_run_id VARCHAR(191) NULL,
  result_json JSON NULL,
  error_message TEXT NULL,
  created_by INT NULL,
  started_at DATETIME NULL,
  completed_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_imaj_idempotency (idempotency_key),
  KEY idx_imaj_claim (status, available_at, lease_expires_at),
  KEY idx_imaj_project (project_id, created_at),
  CONSTRAINT fk_imaj_project FOREIGN KEY (project_id) REFERENCES ipca_manual_ai_projects(id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_imaj_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
